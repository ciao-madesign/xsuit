// Records a SHA-256 of every rule, effect, source, adapter and schema file in rules/integrity.json.
// Run after a REVIEWED change to that data: `npm run lock`. CI fails when the data and the lock differ,
// so rules and adapters cannot change without someone deliberately signing off the new content.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

export const LOCKED_DIRS = ["rules", "adapters", "schemas"];
export function hashes() {
  const out = {};
  for (const dir of LOCKED_DIRS)
    for (const f of readdirSync(dir)
      .filter((x) => x.endsWith(".json") && x !== "integrity.json")
      .sort())
      out[`${dir}/${f}`] = createHash("sha256")
        .update(readFileSync(`${dir}/${f}`, "utf8").replace(/\r\n/g, "\n"))
        .digest("hex");
  return out;
}

if (process.argv[1] && process.argv[1].endsWith("lock-data.mjs")) {
  const h = hashes();
  writeFileSync(
    "rules/integrity.json",
    JSON.stringify(
      {
        note: "Generated by npm run lock after a reviewed change. See docs/14-security-model.md.",
        files: h,
      },
      null,
      2,
    ) + "\n",
  );
  console.log(`locked ${Object.keys(h).length} data files`);
}
