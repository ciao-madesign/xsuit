// Generates docs/07-evidence-audit.md from rules/*.json so the audit can never drift from the data.
import { readFileSync, writeFileSync } from "node:fs";

const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const sources = read("rules/sources.json");
const rules = [...read("rules/western.json").rules, ...read("rules/china.json").rules];
const order = { strong: 0, moderate: 1, emerging: 2, hypothesis: 3 };
const count = (l) => rules.filter((r) => r.evidence.level === l).length;

let out = `# 07 — Evidence audit

> Generated by \`npm run evidence\` from \`rules/\`. Do not edit by hand.

Every rule must be traceable to a real study or to stated observations, with its limits. This page lists each rule, what supports it and what the evidence does **not** show.

**Levels:** strong = two or more independent studies/reviews; moderate = at least one study/review; emerging = indirect or proxy measures; hypothesis = observation or design guess, to be validated (a validation plan is mandatory).

**Totals:** ${rules.length} rules: ${count("strong")} strong, ${count("moderate")} moderate, ${count("emerging")} emerging, ${count("hypothesis")} hypothesis.

## Sources

| id | kind | source | sample | primary text verified |
|---|---|---|---|---|
`;
for (const s of sources)
  out += `| ${s.id} | ${s.kind} | ${s.authors} (${s.year}), [${s.title}](${s.url}) | ${s.sample} | ${s.verified ? `yes (${s.checkedOn})` : `**no** (${(s.attempts ?? ["not yet attempted"]).join(" ")})`} |\n`;

const dims = read("rules/dimensions.json").dimensions;
const profilesData = read("rules/profiles.json");
out +=
  "\n## Dimensions, poles and rules\n\nA profile is a configuration: one pole per dimension, or nothing (the page stays as it is). Each rule belongs to one pole of one dimension and has its own version.\n\n| dimension | pole | rule | version | evidence | last reviewed | in profiles |\n|---|---|---|---|---|---|---|\n";
for (const d of dims)
  for (const p of d.poles) {
    const rs = rules.filter((r) => r.dimension === d.id && r.pole === p.id);
    const inProfiles =
      profilesData
        .filter((x) => x.configuration[d.id] === p.id)
        .map((x) => x.id)
        .join(", ") || "none";
    for (const r of rs)
      out += `| ${d.name} | ${p.name} | ${r.id} | ${r.version} | ${r.evidence.level} | ${r.lastReviewed ?? "never"} | ${inProfiles} |\n`;
  }

const fx = read("rules/effects.json");
out += "\n## Effect catalog (concrete CSS)\n\n" + fx.note + "\n\n";
for (const e of fx.effects)
  out += `- \`${e.key}\`: \`${e.declarations.join("; ")}\`\n  - Basis: ${e.basis}\n  - Constraints: ${e.constraints.join(" ")}\n  - Used by: ${e.ruleIds.join(", ")}\n`;
const cs = fx.contrastSimulation;
out += `\nContrast simulation: ${cs.what}\n\n- Method: ${cs.method}\n`;
for (const r of cs.results)
  out += `- ${r.filter}: ${r.fallBelow4_5Percent}% of passing pairs fall below 4.5:1\n`;
out += `- Correction: ${cs.correction}\n- Caveat: ${cs.caveat}\n`;
out += "\nNo effect (on purpose):\n\n";
for (const e of fx.intentionallyEmpty) out += `- \`${e.key}\`: ${e.reason}\n`;
out += "\n## Rules\n";
for (const r of [...rules].sort(
  (a, b) => order[a.evidence.level] - order[b.evidence.level] || a.id.localeCompare(b.id),
)) {
  out += `\n### \`${r.id}\` — ${r.evidence.level}\n\n`;
  out += `- **Action:** ${r.description} (${r.profile}, ${r.mode}, risk ${r.risk})\n`;
  out += `- **Why:** ${r.rationale}\n- **Supported by:**\n`;
  for (const s of r.evidence.sources) out += `  - \`${s.id}\`, ${s.locator} — ${s.supports}\n`;
  out += `- **Does not show:**\n`;
  for (const g of r.evidence.gaps) out += `  - ${g}\n`;
  if (r.evidence.validationPlan) out += `- **Validation plan:** ${r.evidence.validationPlan}\n`;
  out += `- **Limits:** ${r.limits.join(" ")}\n- **Test results:** ${r.testResults.length ? r.testResults.length + " recorded" : "none yet"}\n`;
}
writeFileSync("docs/07-evidence-audit.md", out);
console.log(`wrote docs/07-evidence-audit.md (${rules.length} rules)`);
